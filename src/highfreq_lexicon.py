def _word_pinyin(word: str) -> str:
    """把词组转成『声母-韵母拼接』的紧凑拼音串，供比对。
    多音字优先按放射语境读音覆盖（_RAD_POLYPHONE）。"""
    if _PY is None:
        return ""
    cached = _WORD_PINYIN.get(word)
    if cached is not None:
        return cached
    try:
        # 逐字取读音（errors="default" 非汉字原样返回，保证一字一音对齐），
        # 再对放射多音字做语境覆盖。
        from pypinyin import pinyin, Style
        parts = pinyin(word, style=Style.NORMAL, errors="default")
        py_parts = []
        for ch, plist in zip(word, parts):
            base = plist[0].lower() if plist else ""
            py_parts.append(_RAD_POLYPHONE.get(ch, base))
        py = "".join(py_parts)
    except Exception:
        py = ""
    _WORD_PINYIN[word] = py
    return py


def _pinyin_build_index() -> Dict[int, Dict[str, List[str]]]:
    """按长度分桶建立『拼音 → 词组』索引，供读音相似查询。
    返回 {词长: {拼音: [词组...]}}。"""
    buckets: Dict[int, Dict[str, List[str]]] = {}
    for word, _cat in _HIGHFREQ_WORDS:
        n = len(word)
        if n < 2:
            continue
        py = _word_pinyin(word)
        if not py:
            continue
        buckets.setdefault(n, {}).setdefault(py, []).append(word)
    return buckets


# 长度 → {拼音: [词组]}
_INDEX = _pinyin_build_index()

# 2026-08-24 性能优化：预构建 word→category 映射，避免 O(n) 重复扫描
_WORD_CATEGORY: Dict[str, str] = {word: cat for word, cat in _HIGHFREQ_WORDS}

# 上下文敏感词排除表：这些串虽然读音与某高频词相同/相似，但在真实报告中是
# 「核心词 + 动词/虚词」的合法句法组合（如『右肺见磨玻璃影』里『肺见』=肺+见），
# 属滑窗切词的固有误判。逐一人工复核后列入，避免 R19 误报。
_HF_IGNORE: Set[str] = {
    "肺见",   # 肺 + 见(见到) —— 高频误判，见 test_r19 反例
    "见右", "见左",  # 见 + 方位
    "为右", "为左", "为双",   # 为 + 方位
    "以右", "以左", "以上", "以下",   # 方位/程度虚词
    "一肺", "双肺见", "右肺见", "左肺见",  # 常见组合
}


def _edit_distance(a: str, b: str) -> int:
    """经典编辑距离（用于拼音串近似比对）。"""
    if a == b:
        return 0
    if not a:
        return len(b)
    if not b:
        return len(a)
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def _pinyin_similar(py_a: str, py_b: str) -> bool:
    """判定两个拼音串是否『读音相似』（同音 或 编辑距离≤1）。"""
    if py_a == py_b:
        return True
    if abs(len(py_a) - len(py_b)) > 1:
        return False
    return _edit_distance(py_a, py_b) <= 1


def find_homophone_suggestions(segment: str,
                               top_k: int = 3) -> List[Tuple[str, str, float, str]]:
    """给定一个可疑片段，返回读音相似的高频正确词候选。

    返回 [(正确词, 类别, 相似度, 类型)]（类型 exact=同音/near=近音/shape=形近），按相似度降序；未安装 pypinyin 时返回空。
    """
    if _PY is None or not segment:
        return []
    seg_py = _word_pinyin(segment)
    if not seg_py:
        return []
    n = len(segment)
    cand: List[Tuple[str, str, float, str]] = []
    # 同长优先；也允许 ±1 长（少一字/多一字）
    for ln in (n, n - 1, n + 1):
        if ln < 2 or ln > 6:
            continue
        bucket = _INDEX.get(ln, {})
        for py, words in bucket.items():
            if not _pinyin_similar(seg_py, py):
                continue
            dist = _edit_distance(seg_py, py)
            sim = 1.0 - dist / max(len(seg_py), len(py), 1)
            kind = "exact" if dist == 0 else "near"  # 同音/近音（2026-08-18 加类型标记）
            for w in words:
                cat = _WORD_CATEGORY.get(w, "")  # O(1) 查找替代 O(n) 扫描
                cand.append((w, cat, round(sim, 3), kind))
    # P1 形近字补充：读音不相似但形近（五笔/形码/OCR 误识）的候选也纳入，
    # 相似度记 0.9（低于同音 1.0 / 近音 0.98，但高于 R19 触发阈值时仍可检出）
    cand_words = {x for x, _, _, _ in cand}  # 2026-08-24: 用 set 替代 list 查找
    for ln in (n,):
        bucket = _INDEX.get(ln, {})
        for py, words in bucket.items():
            for w in words:
                if _shape_similar_word(segment, w):
                    if w not in cand_words:
                        cat = _WORD_CATEGORY.get(w, "")  # O(1) 查找
                        cand.append((w, cat, 0.9, "shape"))
                        cand_words.add(w)
    cand.sort(key=lambda t: -t[2])
    # 去重（同词多类别只留一个）
    seen: Set[str] = set()
    dedup: List[Tuple[str, str, float, str]] = []
    for w, c, s, k in cand:
        if w in seen:
            continue
        seen.add(w)
        dedup.append((w, c, s, k))
        if len(dedup) >= top_k:
            break
    return dedup


