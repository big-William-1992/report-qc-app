def _shape_similar_word(word_a: str, word_b: str) -> bool:
    """两词『形近』判定：长度相同且逐字比对，形近字对数 ≥ 1 且其余字相同。
    形近字主要特征：单个错字时（如 未梢→末梢）非常有效。"""
    if len(word_a) != len(word_b):
        return False
    diff = 0
    for ca, cb in zip(word_a, word_b):
        if ca == cb:
            continue
        diff += 1
        if diff > 1:
            return False
        if cb not in _SHAPE_MAP.get(ca, set()):
            return False
    return diff == 1


