# ===== 报告生成 =====
def generate_normal_report(modality: str = "胸部CT") -> str:
    """生成一份正常报告（零错别字）"""
    tmpl = TEMPLATES.get(modality, TEMPLATES["胸部CT"])

    # 随机选 2-4 条发现 + 1-3 条印象，增加多样性
    n_findings = random.randint(2, min(4, len(tmpl["findings"])))
    n_impression = random.randint(1, min(3, len(tmpl["impression"])))

    findings = random.sample(tmpl["findings"], n_findings)
    impression = random.sample(tmpl["impression"], n_impression)

    report = "检查所见："
    report += "".join(findings)
    report += "诊断印象："
    report += "".join(impression)

    return report


def inject_typo(text: str, n_typos: int = 1) -> str:
    """在文本中注入错别字，确保注入后文本一定与原文不同。

    修复点：
    1. 过滤掉 correct == typo 的空替换规则（如 ("大小正常","大小正常")），
       这类规则替换后文本不变，会导致 has_typo=True 但实际无 diff。
    2. 注入完成后校验 result != text，若未改变则用备用规则集重试。
    3. 增加"字符替换"类 typo 的适用性：减少"字符删除"（如 "未见明显"→"未见明"）
       导致级联位移的比例，降低滑窗检测完全失效的风险。
    """
    all_rules = []
    seen = set()
    for category, rules in TYPO_RULES.items():
        for correct, typo in rules:
            # 过滤掉 correct == typo 的空替换规则
            if correct not in seen and correct != typo:
                all_rules.append((correct, typo))
                seen.add(correct)

    applicable = [(correct, typo) for correct, typo in all_rules if correct in text]

    if not applicable:
        return text

    chosen = random.sample(applicable, min(n_typos, len(applicable)))

    result = text
    for correct, typo in chosen:
        result = result.replace(correct, typo, 1)

    # 兜底校验：若 result 与 text 相同（所有替换均未生效），重试
    if result == text and applicable:
        # 换一批规则重试
        alt = [r for r in applicable if r not in chosen]
        if alt:
            chosen2 = random.sample(alt, min(n_typos, len(alt)))
        else:
            chosen2 = chosen
        for correct, typo in chosen2:
            result = result.replace(correct, typo, 1)

    return result


def generate_typo_report(modality: str = "胸部CT", n_typos: int = 2) -> Tuple[str, str]:
    """生成一份含错别字的报告，返回 (报告文本, 原始正常文本)"""
    normal = generate_normal_report(modality)
    typo = inject_typo(normal, n_typos)
    return typo, normal


def generate_test_dataset(n_normal: int = 50, n_typo: int = 50, seed: int = 42) -> List[dict]:
    """生成完整测试数据集"""
    random.seed(seed)
    dataset = []

    modalities = list(TEMPLATES.keys())

    # 正常报告：按模态均匀分布
    per_modality_normal = n_normal // len(modalities)
    for mod in modalities:
        for i in range(per_modality_normal):
            text = generate_normal_report(mod)
            dataset.append({
                "id": f"normal_{mod}_{i:03d}",
                "modality": mod,
                "text": text,
                "has_typo": False,
            })

    # 错误报告：按模态均匀分布
    per_modality_typo = n_typo // len(modalities)
    for mod in modalities:
        for i in range(per_modality_typo):
            n_typo_injected = random.randint(1, 3)
            typo_text, normal_text = generate_typo_report(mod, n_typos=n_typo_injected)
            dataset.append({
                "id": f"typo_{mod}_{i:03d}",
                "modality": mod,
                "text": typo_text,
                "normal_text": normal_text,
                "has_typo": True,
            })

    random.shuffle(dataset)
    return dataset


